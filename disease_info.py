def get_disease_info(disease_name):

    # Handle healthy plants
    if "healthy" in disease_name.lower():
        info = DISEASE_INFO.get(disease_name)

        if info:
            return info

    # Handle background images
    if disease_name == "Background_without_leaves":
        return {
            "title": "Leaf Not Detected",
            "symptoms": "The image may not contain a clear plant leaf.",
            "cause": "The uploaded image may show background or an unsuitable object.",
            "prevention": "Take a clear photograph of a single plant leaf.",
            "treatment": "Upload another clear leaf image."
        }

    # Return matching disease information
    return DISEASE_INFO.get(disease_name, {
        "title": disease_name.replace("___", " - ").replace("_", " "),
        "symptoms": "A possible disease pattern was identified.",
        "cause": "The exact cause requires further examination.",
        "prevention": "Maintain plant hygiene and monitor affected leaves.",
        "treatment": "Consult a local agricultural expert for confirmation and treatment advice."
    })
